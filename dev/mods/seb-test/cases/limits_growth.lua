-- limits_growth.lua: map generation, plans, project retention and the work
-- budget (regions 60-69, DESIGN.md D43-D45). Every scenario has a force of
-- its own, with its own limits (set_limits) and network.
--   map:     a dry run never has the game make map: charted_only = false
--            over land never generated closes "uncharted" and generates
--            nothing, over generated land it plans; real remote growth with
--            charted_only = false still generates, as documented
--   plans:   plans = 2: a new plan stops the oldest live one (planned ones
--            count), says so, and plans never count toward projects
--   ended:   forty start + stop cycles leave the newest ENDED_PROJECTS_KEPT
--            ended projects; a forgotten one goes with its marks, and its
--            copy carries on as a stopped project's would
--   budget:  work = 100 against 0, same design and network: the held plan
--            falls behind, waits at the busy gate, and still finishes; a
--            normal design at the default share keeps pace with no limit
--   preview: a plan pastes no look-only ghost over another team's entity

local check = require("lib.check")
local rig = require("lib.rig")

local case = { name = "limits_growth" }

local MAP, PLANS, ENDED, FREE, HELD, PACE_FREE, PACE_DEFAULT, PREVIEW = 60, 61, 62, 64, 65, 66, 67, 68
local FAR, FAR_REAL = { x = 20000, y = 6400 }, { x = 24000, y = 6400 }   -- never generated by anything else
local CELL = { rig.panel(1.5, 1.5) }
local GAP = { rig.panel(1.5, 1.5), rig.panel(6.5, 1.5) }   -- 8 x 3, empty from x = 3 to 5
local CYCLES, KEPT = 40, 30   -- KEPT: const.ENDED_PROJECTS_KEPT
local BIG_SIDE, BIG_COLUMNS, BIG_ROWS = 32, 5, 4

local function name(key) return "limits_growth " .. key end

local function grid(side)
  local list = {}
  for x = 0, side - 1 do
    for y = 0, side - 1 do list[#list + 1] = { name = "wooden-chest", position = { x = x + 0.5, y = y + 0.5 } } end
  end
  return list
end

-- A force of the scenario's own with these limits, a site in its region
-- (`wide` for the plans of a big design) and its designs; returns the
-- force's name and the design ids.
local function team(force_name, limits, region, designs, wide)
  local force = rig.own_force(force_name)
  rig.call("set_limits", force, limits)
  local o = rig.region(region)
  rig.floor(game.surfaces.nauvis, wide and rig.box(o, -60, -60, 200, 160) or rig.box(o, -60, -60, 60, 60))
  rig.network(game.surfaces.nauvis, rig.offset(o, -25, -25), nil, force)
  local ids = {}
  for key, entities in pairs(designs) do
    ids[key] = rig.call("register_design", force, rig.blueprint(entities, { label = force_name .. " " .. key }))
  end
  return force, ids
end

local function start(force, design, extra)
  local params = { force = force, surface = game.surfaces.nauvis, design = design, charted_only = false }
  for k, v in pairs(extra) do params[k] = v end
  return rig.call("start_project", params)
end

local function chunk_of(p) return { x = math.floor(p.x / 32), y = math.floor(p.y / 32) } end

local function generated_around(p)
  local c, n = chunk_of(p), 0
  for dx = -2, 2 do
    for dy = -2, 2 do
      if game.surfaces.nauvis.is_chunk_generated({ x = c.x + dx, y = c.y + dy }) then n = n + 1 end
    end
  end
  return n
end

local function neutral_ghosts(box)
  return game.surfaces.nauvis.count_entities_filtered {
    area = { { box.left, box.top }, { box.right, box.bottom } }, type = "entity-ghost", force = "neutral",
  }
end

function case.setup(surface)
  local s = {}
  storage.limits_growth = s
  s.map, s.map_designs = team("seb-lg-map", {}, MAP, { cell = CELL })
  s.plans, s.plans_designs = team("seb-lg-plans", { plans = 2, projects = 1 }, PLANS, { cell = CELL })
  s.ended, s.ended_designs = team("seb-lg-ended", {}, ENDED, { cell = CELL })
  rig.water(surface, rig.box(rig.region(ENDED), 40, 0, 50, 10))
  s.free, s.free_designs = team("seb-lg-free", { work = 0 }, FREE, { big = grid(BIG_SIDE) }, true)
  s.held, s.held_designs = team("seb-lg-held", { work = 100 }, HELD, { big = grid(BIG_SIDE) }, true)
  s.pace_free, s.pace_free_designs = team("seb-lg-pace-free", { work = 0 }, PACE_FREE, { cell = CELL })
  s.pace_default, s.pace_default_designs = team("seb-lg-pace-default", { work = 500 }, PACE_DEFAULT, { cell = CELL })
  s.preview, s.preview_designs = team("seb-lg-preview", {}, PREVIEW, { gap = GAP })
  local o = rig.region(PREVIEW)
  s.foreign_chest = surface.create_entity { name = "iron-chest", position = rig.offset(o, 4.5, 1.5), force = rig.FORCE }
  surface.create_entity { name = "iron-chest", position = rig.offset(o, 20.5, 1.5), force = s.preview }
  s.far_before = generated_around(FAR)
end

local function start_map(s)
  local o = rig.region(MAP)
  s.far_plan = start(s.map, s.map_designs.cell, { dry_run = true, point = { x = FAR.x + 0.5, y = FAR.y + 0.5 }, max_instances = 3 })
  s.near_plan = start(s.map, s.map_designs.cell, { dry_run = true, area = rig.box(o, 0, 0, 9, 3), preview_ghosts = 1 })
  s.far_real = start(s.map, s.map_designs.cell, { build_position = FAR_REAL, materials = false, max_instances = 1 })
  check.truthy(name("map projects start"), s.far_plan and s.near_plan and s.far_real)
end

-- A third plan stops the oldest; a real project still starts beside two
-- plans (they never count toward projects), a second one does not.
local function start_plans(s)
  local o, design = rig.region(PLANS), s.plans_designs.cell
  s.plan_a = start(s.plans, design, { dry_run = true, area = rig.box(o, 0, 0, 6, 3) })
  s.plan_b = start(s.plans, design, { dry_run = true, area = rig.box(o, 0, 10, 6, 13) })
  local real = start(s.plans, design, { build_position = rig.offset(o, 0, 20), max_instances = 1, materials = false })
  check.truthy(name("plans never count toward projects"), real)
  local refused, reason = start(s.plans, design, { build_position = rig.offset(o, 0, 30), max_instances = 1 })
  check.same(name("plans a second real project is refused"), { refused, reason }, { nil, "too-many-projects" })
  local dropped
  s.plan_c, dropped = start(s.plans, design, { dry_run = true, area = rig.box(o, 0, 40, 6, 43) })
  check.truthy(name("plans a third plan always starts"), s.plan_c)
  check.same(name("plans the starter learns which plan stopped"), dropped, { s.plan_a })
  local a = rig.call("get_project", s.plan_a) or {}
  local last = a.history and a.history[#a.history] or {}
  check.same(name("plans the oldest is stopped, and says why"), { a.state, last.kind, last.limit }, { "stopped", "replaced", 2 })
  check.eq(name("plans the second stays"), (rig.call("get_project", s.plan_b) or {}).state, "growing")
end

local function start_ended(s)
  local o, design = rig.region(ENDED), s.ended_designs.cell
  s.watered = start(s.ended, design, { build_position = rig.offset(o, 42, 2), materials = false, max_instances = 1 })
  s.built = start(s.ended, design, { build_position = rig.offset(o, 0, 0), max_instances = 1 })
end

local function start_budget(s)
  local box = function(region) return rig.box(rig.region(region), 0, 0, BIG_SIDE * BIG_COLUMNS, BIG_SIDE * BIG_ROWS) end
  s.free_plan = start(s.free, s.free_designs.big, { dry_run = true, area = box(FREE) })
  s.held_plan = start(s.held, s.held_designs.big, { dry_run = true, area = box(HELD) })
  local fill = function(region) return rig.box(rig.region(region), 0, 0, 9, 9) end
  s.fill_free = start(s.pace_free, s.pace_free_designs.cell, { area = fill(PACE_FREE) })
  s.fill_default = start(s.pace_default, s.pace_default_designs.cell, { area = fill(PACE_DEFAULT) })
  s.busy_seen = false
  check.truthy(name("budget projects start"), s.free_plan and s.held_plan and s.fill_free and s.fill_default)
end

function case.start()
  local s = storage.limits_growth
  start_map(s)
  start_plans(s)
  start_ended(s)
  start_budget(s)
  s.preview_plan = start(s.preview, s.preview_designs.gap, {
    dry_run = true, preview_ghosts = 3, area = rig.box(rig.region(PREVIEW), 0, 0, 24, 3), directions = { defines.direction.east },
  })
end

local function project(id) return rig.call("get_project", id) or {} end

-- The held plan waits at the busy gate between steps; a sample finds it.
local function sample_busy(s)
  local p = project(s.held_plan)
  if p.gate == "busy" or (p.status and p.status.reason == "busy") then s.busy_seen = true end
end

local function check_map(s)
  local far, near = project(s.far_plan), project(s.near_plan)
  check.same(name("map a plan over land never generated closes uncharted"),
    { far.count, far.closed and far.closed.uncharted, far.status and far.status.level }, { 0, 1, "planned" })
  check.same(name("map the plan generated no chunk"), { s.far_before, generated_around(FAR) }, { 0, 0 })
  check.same(name("map a plan over generated land plans"), { near.count, near.status and near.status.level }, { 3, "planned" })
  check.eq(name("map its first copy shows as ghosts"), neutral_ghosts(rig.box(rig.region(MAP), 0, 0, 3, 3)), 1)
end

-- A plan waiting to be built is live too: a fourth plan stops the second,
-- and its outlines leave the map.
local function check_plans(s)
  local o = rig.region(PLANS)
  local b_box = rig.box(o, -1, 9, 7, 14)
  check.same(name("plans both live plans are planned"),
    { project(s.plan_b).status.level, project(s.plan_c).status.level }, { "planned", "planned" })
  check.eq(name("plans a planned plan draws its copies"), rig.drawn(game.surfaces.nauvis, b_box).rectangle, 2)
  local d, dropped = start(s.plans, s.plans_designs.cell, { dry_run = true, area = rig.box(o, 0, 50, 6, 53) })
  check.same(name("plans a planned plan waiting to be built counts as live"), { d ~= nil, dropped }, { true, { s.plan_b } })
  check.eq(name("plans a stopped plan draws nothing"), rig.drawn(game.surfaces.nauvis, b_box).rectangle, nil)
end

-- The scenario's copy, a solar panel the network built.
local function copy_of(project_id)
  return rig.instances_of(project_id)[1]
end

local function crosses(o)
  return rig.drawn(game.surfaces.nauvis, rig.box(o, 40, 0, 50, 10))["seb-overlay-blocked"]
end

-- Forty projects of the force started and stopped, one after another.
local function start_and_stop(s, o)
  s.cycles = {}
  for i = 1, CYCLES do
    s.cycles[i] = start(s.ended, s.ended_designs.cell, { build_position = rig.offset(o, 0, 20 + 4 * i), materials = false })
    rig.call("stop_project", s.cycles[i])
  end
  local alive = 0
  for _, id in ipairs(s.cycles) do if rig.call("get_project", id) then alive = alive + 1 end end
  return alive
end

local function check_ended(s)
  local watered, built = project(s.watered), project(s.built)
  local o = rig.region(ENDED)
  check.same(name("ended both finish"), { watered.state, built.state, built.count }, { "finished", "finished", 1 })
  check.truthy(name("ended a water close is marked"), (crosses(o) or 0) > 0)
  s.copy = (copy_of(s.built) or {}).id
  local alive = start_and_stop(s, o)
  check.same(name("ended the newest are kept"), { alive, rig.call("get_limits", s.ended).ended_projects }, { KEPT, KEPT })
  check.same(name("ended the oldest are forgotten"),
    { rig.call("get_project", s.cycles[CYCLES - KEPT]), project(s.cycles[CYCLES - KEPT + 1]).state }, { nil, "stopped" })
  check.same(name("ended finished projects are forgotten too"), { rig.call("get_project", s.watered), rig.call("get_project", s.built) }, {})
  check.eq(name("ended a forgotten project's marks go"), crosses(o), nil)
  check.eq(name("ended stopping a forgotten project finds nothing"), rig.call("stop_project", s.watered), false)
  local copy = rig.call("get_instance", s.copy or 0) or {}
  check.same(name("ended its copy stays"), { copy.state, copy.project_id }, { "complete", s.built })
  check.eq(name("ended its copy can still be removed"), rig.call("remove_instance", s.copy or 0), true)
end

local function check_budget_mid(s)
  sample_busy(s)
  local free, held = project(s.free_plan), project(s.held_plan)
  check.truthy(name("budget the held plan is behind"), (held.count or 0) < (free.count or 0),
    "held " .. tostring(held.count) .. ", free " .. tostring(free.count))
  check.eq(name("budget a normal design keeps pace at the default share"), project(s.fill_default).count, project(s.fill_free).count)
end

local function check_budget_end(s)
  local free, held = project(s.free_plan), project(s.held_plan)
  local all = BIG_COLUMNS * BIG_ROWS
  check.same(name("budget both plans finish"), { free.count, held.count, held.status and held.status.level }, { all, all, "planned" })
  check.truthy(name("budget the held plan waited at the busy gate"), s.busy_seen)
  local busy = 0
  for _, entry in ipairs(held.history or {}) do
    if entry.kind == "waiting" and entry.reason == "busy" then busy = busy + entry.count end
  end
  check.truthy(name("budget the wait is in the history, not once per step"), busy >= 1 and busy < all, "busy lines " .. busy)
  local f, d = project(s.fill_free), project(s.fill_default)
  check.same(name("budget the normal fills finish alike"), { d.state, d.count }, { f.state, f.count })
end

local function check_preview(s)
  local o, plan = rig.region(PREVIEW), project(s.preview_plan)
  check.eq(name("preview plans all three copies"), plan.count, 3)
  -- Only what stands under a copy's parts bars its preview (under.lua): the
  -- other team's chest in the first copy's gap does not.
  check.same(name("preview another team's chest in a copy's gap no bar, own chest no bar"),
    { neutral_ghosts(rig.box(o, 0, 0, 8, 3)), neutral_ghosts(rig.box(o, 8, 0, 16, 3)), neutral_ghosts(rig.box(o, 16, 0, 24, 3)) },
    { 2, 2, 2 })
  check.eq(name("preview the other team's chest is left alone"),
    s.foreign_chest.valid and not s.foreign_chest.to_be_deconstructed(), true)
end

local function check_far_real(s)
  local real = project(s.far_real)
  -- What the new land holds (water, there, with this map seed) is the map's
  -- business: the project waited for it and was tried on it.
  local waited = false
  for _, entry in ipairs(real.history or {}) do waited = waited or (entry.kind == "waiting" and entry.reason == "chunks") end
  check.same(name("map real growth off charted land still generates"),
    { game.surfaces.nauvis.is_chunk_generated(chunk_of(FAR_REAL)), waited, real.gate, real.closed and real.closed.uncharted },
    { true, true })
  -- A retired copy whose project is gone may be forgotten as well (D45).
  local copy = rig.call("get_instance", s.copy or 0)
  check.truthy(name("ended the removed copy of a forgotten project retires"),
    s.copy and (copy == nil or copy.state == "retired"), check.show(copy))
end

local function at(fn) return function() fn(storage.limits_growth) end end

case.checks = {
  [120] = at(sample_busy), [180] = at(sample_busy), [240] = at(check_budget_mid), [300] = at(check_map),
  [360] = at(check_plans), [420] = at(sample_busy), [480] = at(check_preview), [600] = at(check_ended),
  [1200] = at(check_budget_end), [2400] = at(check_far_real),
}

return case
